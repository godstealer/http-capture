import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../apps/frontend/src/formatResponse.ts', import.meta.url), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const path = new URL('../.local/format-response-test.mjs', import.meta.url);
fs.writeFileSync(path, output);
const { formatResponse, responseLanguage } = await import(path.href);
assert.equal(responseLanguage('Text/HTML; charset=UTF-8'), 'html');
assert.equal(responseLanguage('application/problem+json'), 'json');
assert.equal(responseLanguage('application/javascript'), 'babel');
assert.equal(responseLanguage('text/plain'), 'text');
assert.match(await formatResponse('<html><body><main><h1>Hi</h1><p>World</p></main></body></html>', 'html'), /\n\s+<body>/);
assert.match(await formatResponse('function hello(){const a={x:1};return a.x;}', 'babel'), /\n\s+const a/);
assert.match(await formatResponse('body{color:red;background:black}', 'css'), /\n\s+color: red/);
assert.match(await formatResponse('{"a":1,"nested":{"b":[1,2]}}', 'json'), /"a": 1/);
assert.equal(await formatResponse('  original\n\ttext', 'text'), '  original\n\ttext');
await assert.rejects(() => formatResponse('function { broken', 'babel'));
await assert.rejects(() => formatResponse('x'.repeat(1024 * 1024 + 1), 'html'));
console.log('Response formatting: HTML, JS, CSS, JSON, MIME detection, original text and failure/size handling passed.');
